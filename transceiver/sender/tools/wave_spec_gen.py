# -*- coding: utf-8 -*-
"""从真实数据 PSD 拟合每类 12 个正弦分量，生成 C 头文件（整数合成器）。

输出：D:\\FPGAProject\\firmware\\sle_wave_gen.h
      D:\\FPGAProject\\firmware\\wave_spec_ref.bin（每类 4 窗，int8，用于验证）
"""
import os
import sys

import numpy as np
import pandas as pd
import torch

sys.path.insert(0, r"D:\DSH\FPGA\wdcnn_xjty\scripts")
from WDCNN_ReLU import WDCNN_ReLU  # noqa: E402

FS = 8000
WIN = 5120
NSIN = 12
OUT = r"D:\FPGAProject\firmware"

# 真实量化域（int8）每类 rms
_rms = {}
for dev in range(8):
    _rms[dev] = None

df = pd.read_csv(r"D:\DSH\FPGA\wdcnn_xjty\data\XJTY_train_amp.csv", header=None)
y = df.iloc[:, -1].values.astype(int)
X = df.iloc[:, :-1].values.astype(np.float64)
n = X.shape[1]
han = np.hanning(n)
F = np.fft.rfftfreq(n, 1.0 / FS)

# int8 域目标 rms（来自 wd_input.bin 的实测）
TARGET_RMS = [2.90, 17.41, 2.38, 27.0]   # class3 稍降到 27，避免过度削顶
NOISE_FRAC = 0.06

tables = []
for c in range(4):
    Xc = X[y == c]
    P = (np.abs(np.fft.rfft(Xc * han, axis=1)) ** 2).mean(axis=0)
    order = np.argsort(P)[::-1]
    peaks = []
    for i in order:
        if F[i] < 5:
            continue
        if all(abs(F[i] - p) > 6 for p in peaks):
            peaks.append(float(F[i]))
        if len(peaks) >= NSIN:
            break
    amps = np.array([np.sqrt(P[np.argmin(np.abs(F - f))]) for f in peaks])
    amps = amps / np.sqrt((amps ** 2).sum() / 2.0) * TARGET_RMS[c]
    tables.append((np.array(peaks), amps))
    print("class %d rms=%.2f  f=%s" % (c, TARGET_RMS[c],
          ', '.join('%.0f:%.2f' % (f, a) for f, a in zip(peaks, amps))))

SINE = np.round(np.sin(2 * np.pi * np.arange(256) / 256.0) * 32767).astype(np.int32)


def gen_window(c, seed):
    """整数合成一窗 5120 点 int8，与 C 实现逐位一致。"""
    peaks, amps = tables[c]
    inc = np.round(peaks * 2 ** 32 / FS).astype(np.uint64)
    amp11 = np.round(amps * 2048).astype(np.int64)
    rnd = (seed * 2654435761 + 12345) & 0xFFFFFFFF
    ph = []
    for _ in range(NSIN):
        rnd = (rnd * 1664525 + 1013904223) & 0xFFFFFFFF
        ph.append(rnd)
    ph = np.array(ph, dtype=np.uint64)
    noise_amp = int(round(NOISE_FRAC * TARGET_RMS[c]))
    out = np.empty(WIN, dtype=np.int8)
    for i in range(WIN):
        ph += inc
        idx = (ph >> 24).astype(np.int64) & 0xFF
        acc = int((((SINE[idx] * amp11) >> 11)).sum()) >> 15
        rnd = (rnd * 1664525 + 1013904223) & 0xFFFFFFFF
        nz = (((int(rnd & 1023) - 512)) * noise_amp) >> 9
        v = acc + nz
        out[i] = 127 if v > 127 else (-128 if v < -128 else v)
    return out


# ---- 验证：跑分类模型 ----
m = WDCNN_ReLU(4)
m.load_state_dict(torch.load(r"D:\DSH\FPGA\wdcnn_xjty\output\wdcnn_relu.pth",
                             map_location="cpu"))
m.eval()
S = 5.08732560604007
samples, labels = [], []
for c in range(4):
    for k in range(4):
        samples.append(gen_window(c, 1000 + k))
        labels.append(c)
samples = np.array(samples, dtype=np.int8)
with torch.no_grad():
    pred = m(torch.from_numpy(samples.astype(np.float32) / S).unsqueeze(1)).argmax(1).numpy()
print("verify pred:", pred, "expect:", np.array(labels))
print("accuracy = %.2f" % (pred == np.array(labels)).mean())
for c in range(4):
    seg = samples[c * 4].astype(np.float64)
    print("  class %d rms=%.2f peak=%d" % (c, np.sqrt((seg ** 2).mean()), np.abs(seg).max()))

samples.tofile(os.path.join(OUT, 'wave_spec_ref.bin'))

# ---- 生成 C 头文件 ----
lines = []
lines.append('#ifndef SLE_WAVE_GEN_H')
lines.append('#define SLE_WAVE_GEN_H')
lines.append('/* auto-generated by wave_spec_gen.py : spectral synthesizer, per-class 12 sines */')
lines.append('')
lines.append('#include <stdint.h>')
lines.append('')
lines.append('#define WG_FS          8000')
lines.append('#define WG_PTS_PER_PKT 160')
lines.append('#define WG_PKTS_PER_WIN 32')
lines.append('#define WG_WIN_ELEMS   (WG_PTS_PER_PKT * WG_PKTS_PER_WIN)')
lines.append('#define WG_NSIN        %d' % NSIN)
lines.append('#define WG_NCLASS      4')
lines.append('')
lines.append('#define SLE_WIN_ELEMS WG_WIN_ELEMS')
lines.append('#define SLE_WIN_NUM   32')
lines.append('')
lines.append('#ifndef WAVE_DEV_ID')
lines.append('#define WAVE_DEV_ID 1')
lines.append('#endif')
lines.append('')
lines.append('static const int16_t WG_SINE[256] = {')
for i in range(0, 256, 12):
    lines.append('    ' + ', '.join(str(int(v)) for v in SINE[i:i + 12]) + ',')
lines.append('};')
lines.append('')
for c in range(4):
    peaks, amps = tables[c]
    inc = np.round(peaks * 2 ** 32 / FS).astype(np.uint64).astype(np.int64)
    amp11 = np.round(amps * 2048).astype(np.int64)
    lines.append('static const uint32_t WG_INC_%d[WG_NSIN] = {%s};'
                 % (c, ', '.join('%du' % (v & 0xFFFFFFFF) for v in inc)))
    lines.append('static const int32_t WG_AMP_%d[WG_NSIN] = {%s};'
                 % (c, ', '.join('%d' % v for v in amp11)))
    lines.append('')
lines.append('static const uint32_t *const WG_INC[WG_NCLASS] = {%s};'
             % ', '.join('WG_INC_%d' % c for c in range(4)))
lines.append('static const int32_t *const WG_AMP[WG_NCLASS] = {%s};'
             % ', '.join('WG_AMP_%d' % c for c in range(4)))
lines.append('static const int16_t WG_NOISE[WG_NCLASS] = {%s};'
             % ', '.join('%d' % int(round(NOISE_FRAC * TARGET_RMS[c])) for c in range(4)))
lines.append('static const uint8_t WG_CLASS[8] = {0, 0, 1, 1, 2, 2, 3, 3};')
lines.append('')
lines.append('#define WG_CLS  (WG_CLASS[(WAVE_DEV_ID) - 1])')
lines.append('')
lines.append('static uint32_t wg_ph[WG_NSIN];')
lines.append('static uint32_t wg_rnd;')
lines.append('static int32_t  wg_pos;')
lines.append('')
lines.append('static void wave_gen_init(void)')
lines.append('{')
lines.append('    uint32_t i;')
lines.append('    wg_rnd = 0x12345678u;')
lines.append('    wg_pos = 0;')
lines.append('    for (i = 0; i < (uint32_t)WG_NSIN; i++) {')
lines.append('        wg_rnd = wg_rnd * 1664525u + 1013904223u;')
lines.append('        wg_ph[i] = wg_rnd;')
lines.append('    }')
lines.append('}')
lines.append('')
lines.append('static void wave_gen_fill(int8_t *dst, uint16_t n)')
lines.append('{')
lines.append('    uint16_t i;')
lines.append('    uint32_t k;')
lines.append('    const uint32_t *inc = WG_INC[WG_CLS];')
lines.append('    const int32_t *amp = WG_AMP[WG_CLS];')
lines.append('    int32_t noise = WG_NOISE[WG_CLS];')
lines.append('    for (i = 0; i < n; i++) {')
lines.append('        int32_t acc = 0;')
lines.append('        int32_t v;')
lines.append('        if (wg_pos == 0) {')
lines.append('            for (k = 0; k < (uint32_t)WG_NSIN; k++) {')
lines.append('                wg_rnd = wg_rnd * 1664525u + 1013904223u;')
lines.append('                wg_ph[k] = wg_rnd;')
lines.append('            }')
lines.append('        }')
lines.append('        for (k = 0; k < (uint32_t)WG_NSIN; k++) {')
lines.append('            wg_ph[k] += inc[k];')
lines.append('            acc += (int32_t)(((int32_t)WG_SINE[wg_ph[k] >> 24] * amp[k]) >> 11);')
lines.append('        }')
lines.append('        wg_rnd = wg_rnd * 1664525u + 1013904223u;')
lines.append('        acc += (int32_t)((((int32_t)(wg_rnd & 1023u)) - 512) * noise) >> 9;')
lines.append('        wg_pos++;')
lines.append('        if (wg_pos >= WG_WIN_ELEMS) {')
lines.append('            wg_pos = 0;')
lines.append('        }')
lines.append('        v = acc >> 15;')
lines.append('        if (v > 127) {')
lines.append('            v = 127;')
lines.append('        } else if (v < -128) {')
lines.append('            v = -128;')
lines.append('        }')
lines.append('        dst[i] = (int8_t)v;')
lines.append('    }')
lines.append('}')
lines.append('')
lines.append('#endif /* SLE_WAVE_GEN_H */')
lines.append('')

path = os.path.join(OUT, 'sle_wave_gen.h')
with open(path, 'w', encoding='ascii', newline='\n') as f:
    f.write('\n'.join(lines))
print('wrote', path, os.path.getsize(path), 'bytes')
